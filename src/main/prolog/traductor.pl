    validar_genero(Resto, RestoValidado).
validar_genero(Lista, Resultado) :-
    append(Prefijo, [un, grande, casa|Sufijo], Lista),
    append(Prefijo, [una, casa, grande|Sufijo], ListaValidada),
    validar_genero(ListaValidada, Resultado).
validar_genero([Palabra|Resto], [Palabra|RestoValidado]) :-
    validar_genero(Resto, RestoValidado).

traducir_http(Request) :-
    http_read_json_dict(Request, Datos),
    get_dict(texto, Datos, Texto),
    get_dict(propuesta, Datos, Propuesta),
    atom_string(TextoAtom, Texto),
    ( traducir(TextoAtom, PropuestaBasica) -> true ; PropuestaBasica = Texto ),
    maplist(atom_string, PropuestaAtoms, Propuesta),
    validar_genero(PropuestaAtoms, PropuestaValidadaAtoms),
    PropuestaValidada = PropuestaValidadaAtoms,
    atomic_list_concat(PropuestaValidada, ' ', ResultadoAtom),
    atom_string(ResultadoAtom, Resultado),
    atomic_list_concat(PropuestaValidada, ' ', PropuestaFinalAtom),
    atom_string(PropuestaFinalAtom, PropuestaFinal),
    reply_json_dict(_{
        traduccion: Resultado,
        propuesta_basica: PropuestaBasica,
        propuesta_validada: PropuestaFinal,
        reglas_aplicadas: true
    }).

health_http(_Request) :-
    reply_json_dict(_{status: ok, servicio: prolog}).

servidor(PrologPort) :-
    http_server(http_dispatch, [port(PrologPort)]),
    format('Servidor Prolog activo en http://localhost:~w~n', [PrologPort]).

