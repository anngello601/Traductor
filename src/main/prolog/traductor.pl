% ------------------------------------------------------------
% Traducción de frases
% ------------------------------------------------------------
traducir(Frase, Traduccion) :-
    atom_string(Frase, FraseStr),
    split_string(FraseStr, " ", " ", PalabrasStr),
    maplist(string_lower, PalabrasStr, PalabrasMin),
    maplist(atom_string, Palabras, PalabrasMin),
    traducir_palabras(Palabras, Traducidas),
    atomic_list_concat(Traducidas, ' ', Traduccion).

traducir_palabras([], []).
traducir_palabras([P|Resto], [T|Ts]) :-
    (   traduce(en, es, P, _, T)
    ->  true
    ;   T = P              % palabra desconocida: se deja igual
    ),
    traducir_palabras(Resto, Ts).

